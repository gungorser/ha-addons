#!/usr/bin/env python3
"""Add-on start-up: options -> Paperless environment, plus nginx.conf.

Runs as the first s6 oneshot (before the upstream init-start). Every value is
written to the s6 container environment, so all upstream scripts see it.
"""

import json
import os
import secrets
import urllib.request
from pathlib import Path

OPTIONS = Path("/data/options.json")
ENV_DIR = Path("/run/s6/container_environment")
SECRET_FILE = Path("/config/secret_key")
NGINX_CONF = Path("/etc/nginx/nginx.conf")

# Documents live on the "paperless" network storage (mounted at /share/paperless);
# database, search index and model stay in the add-on config folder.
FIXED = {
    "PAPERLESS_DATA_DIR": "/config/data",
    "PAPERLESS_MEDIA_ROOT": "/share/paperless/media",
    "PAPERLESS_CONSUMPTION_DIR": "/share/paperless/consume",
    "PAPERLESS_REDIS": "redis://127.0.0.1:6379",
    "PAPERLESS_BIND_ADDR": "127.0.0.1",
    "PAPERLESS_PORT": "8000",
    # Run as root: the network share does not allow chown to the paperless user.
    "USERMAP_UID": "0",
    "USERMAP_GID": "0",
}

NGINX_TEMPLATE = """daemon off;
worker_processes 1;
pid /run/nginx.pid;
error_log stderr warn;

events {
    worker_connections 512;
}

http {
    access_log off;
    client_max_body_size 0;
    proxy_request_buffering off;
    proxy_read_timeout 600s;

    map $http_upgrade $connection_upgrade {
        default upgrade;
        '' close;
    }
    map $http_x_forwarded_proto $forwarded_proto {
        default $http_x_forwarded_proto;
        '' $scheme;
    }
    # The Ingress panel (an iframe) can post forms with "Origin: null", which
    # Django's CSRF check rejects. Drop that value; the CSRF token is still checked.
    map $http_origin $origin {
        default $http_origin;
        null '';
    }

    server {
        listen 8099;

        proxy_http_version 1.1;
        proxy_set_header Host $http_host;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $forwarded_proto;
        proxy_set_header Origin $origin;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $connection_upgrade;

        # Paperless is served under the Ingress path. Ingress strips that path,
        # the LAN port never has it: both get it added back here. Links that
        # already carry it (generated by Paperless) pass through unchanged.
        location ^~ @PREFIX@/ {
            proxy_pass http://127.0.0.1:8000;
        }
        location / {
            proxy_pass http://127.0.0.1:8000@PREFIX@/;
        }
    }
}
"""


def ingress_entry() -> str:
    """The add-on's Ingress path, e.g. /api/hassio_ingress/<token>."""
    request = urllib.request.Request(
        "http://supervisor/addons/self/info",
        headers={"Authorization": f"Bearer {os.environ['SUPERVISOR_TOKEN']}"},
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        entry = json.load(response)["data"]["ingress_entry"]
    return entry.rstrip("/")


def secret_key() -> str:
    """A stable Django secret key, created on first start."""
    if not SECRET_FILE.exists():
        SECRET_FILE.write_text(secrets.token_urlsafe(50))
        SECRET_FILE.chmod(0o600)
    return SECRET_FILE.read_text().strip()


def flag(value: bool) -> str:
    return "true" if value else "false"


def main() -> None:
    options = json.loads(OPTIONS.read_text())
    prefix = ingress_entry()

    env = dict(FIXED)
    env.update(
        {
            "PAPERLESS_FORCE_SCRIPT_NAME": prefix,
            "PAPERLESS_SECRET_KEY": secret_key(),
            "PAPERLESS_OCR_LANGUAGE": options["ocr_language"],
            "PAPERLESS_TIME_ZONE": options["time_zone"],
            "PAPERLESS_FILENAME_FORMAT": options["filename_format"],
            "PAPERLESS_CONSUMER_RECURSIVE": flag(options["consumer_recursive"]),
            "PAPERLESS_CONSUMER_SUBDIRS_AS_TAGS": flag(
                options["consumer_subdirs_as_tags"]
            ),
            # Network shares send no inotify events: poll the consume folder.
            "PAPERLESS_CONSUMER_POLLING": str(options["consumer_polling"]),
            "PAPERLESS_CSRF_TRUSTED_ORIGINS": ",".join(
                options["csrf_trusted_origins"]
            ),
        }
    )
    if options.get("admin_user") and options.get("admin_password"):
        env["PAPERLESS_ADMIN_USER"] = options["admin_user"]
        env["PAPERLESS_ADMIN_PASSWORD"] = options["admin_password"]
    for extra in options.get("env_vars", []):
        env[extra["name"]] = extra["value"]

    for name, value in env.items():
        (ENV_DIR / name).write_text(value)

    NGINX_CONF.parent.mkdir(parents=True, exist_ok=True)
    NGINX_CONF.write_text(NGINX_TEMPLATE.replace("@PREFIX@", prefix))

    shown = {k: ("***" if "SECRET" in k or "PASSWORD" in k else v) for k, v in env.items()}
    print("[addon-env] Paperless environment:", json.dumps(shown, indent=1))


if __name__ == "__main__":
    main()
